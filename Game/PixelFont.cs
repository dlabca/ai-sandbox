        public static int Width(string text, int scale)
        {
            if (string.IsNullOrEmpty(text)) return 0;
            return text.Length * 6 * scale - scale;
        }

        public static int Height(int scale)
        {
            return 7 * scale;
        }

        public static void Draw(SpriteBatch sb, Texture2D px, string text, int x, int y, int scale, Color color)
        {
            int cx = x;
            for (int i = 0; i < text.Length; i++)
            {
                char ch = char.ToUpperInvariant(text[i]);
                string[] g;
                if (Glyphs.TryGetValue(ch, out g))
                {
                    for (int row = 0; row < 7; row++)
                    {
                        string r = g[row];
                        int col = 0;
                        while (col < 5)
                        {
                            if (r[col] == '#')
                            {
                                int start = col;
                                while (col < 5 && r[col] == '#') col++;
                                sb.Draw(px, new Rectangle(cx + start * scale, y + row * scale, (col - start) * scale, scale), color);
                            }
                            else
                            {
                                col++;
                            }
                        }
                    }
                }
                cx += 6 * scale;
            }
        }
